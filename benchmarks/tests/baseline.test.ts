import { describe, expect, test } from 'bun:test';
import { readMicrobenchJson, SCHEMA_VERSION } from '../src/results.js';
import {
  EXPECTED_SCENARIOS,
  findAllocViolations,
  findContractViolations,
  PENDING_FIRST_CAPTURE,
} from '../src/scenario-contract.js';

/**
 * The violations a suite in `PENDING_FIRST_CAPTURE` produces against a baseline
 * captured before it existed: the suite itself, and each of its rows restated
 * as a missing scenario. Nothing else is excused: a missing row of any other
 * suite, an unexpected suite or row, and a broken headline prefix all still fail.
 */
function pendingViolations(): Set<string> {
  const excused = new Set<string>();
  for (const title of PENDING_FIRST_CAPTURE) {
    excused.add(`missing suite: ${title}`);
    for (const scenario of EXPECTED_SCENARIOS[title] ?? []) {
      excused.add(`missing scenario: ${scenario}`);
    }
  }
  return excused;
}

/**
 * Validates the COMMITTED baseline — the file the published doc and the
 * dashboard both render from.
 *
 * Every check here already existed inside `--markdown`, which is the one code
 * path nothing automated ever runs: the doc is regenerated by hand, so a
 * baseline that drifted out of the contract stayed green in CI and only failed
 * the next time a human typed the command. That is the same shape of hole that
 * let a 3x render regression sit published for three months.
 *
 * Note for whoever adds a check: `benchmarks/results/**` had to be added to the
 * turbo `#test` inputs for this file to be re-run when the baseline changes.
 */

describe('committed baseline', () => {
  const baseline = readMicrobenchJson();

  test('is present and parseable', () => {
    expect(baseline).not.toBeNull();
  });

  test('was captured under the current result schema', () => {
    expect(baseline?.schemaVersion).toBe(SCHEMA_VERSION);
  });

  test('was captured with __DEV__ declared', () => {
    // Undeclared means the render rows measure a JSC unresolvable-global
    // penalty (~270 ns per guarded evaluation) rather than the engine.
    expect(baseline?.devFlag).toBe('false');
  });

  test('satisfies the frozen scenario contract, less the suites pending their first capture', () => {
    const excused = pendingViolations();
    const violations = findContractViolations(baseline?.suites ?? []);
    expect(violations.filter((v) => !excused.has(v))).toEqual([]);
  });

  test('carries none of the suites still listed as pending their first capture', () => {
    // Fails the moment a recapture lands a pending suite, so the capture's PR
    // has to empty PENDING_FIRST_CAPTURE rather than leave an exemption behind.
    const captured = new Set((baseline?.suites ?? []).map((s) => s.title));
    expect(PENDING_FIRST_CAPTURE.filter((title) => captured.has(title))).toEqual([]);
  });

  test('carries the full exact-counter section, all gates passing', () => {
    expect(findAllocViolations(baseline?.alloc ?? [])).toEqual([]);
    for (const row of baseline?.alloc ?? []) {
      expect(row.problems).toEqual([]);
    }
  });

  test('every heap row reached its plateau', () => {
    for (const row of baseline?.heap ?? []) {
      expect(row.converged).toBe(true);
    }
  });

  test('was promoted from several runs, not published from one', () => {
    // A single-run baseline has no spread band, so nothing downstream can tell
    // a real change from this machine's noise.
    expect(baseline?.runs ?? 1).toBeGreaterThan(1);
    for (const suite of baseline?.suites ?? []) {
      for (const r of suite.results) {
        expect(typeof r.bandMinNs).toBe('number');
        expect(typeof r.bandMaxNs).toBe('number');
      }
    }
  });

  test('names the commit it measured, from a clean tree', () => {
    expect(baseline?.gitSha).toMatch(/^[0-9a-f]{12}$/);
    expect(baseline?.gitDirty).toBe(false);
  });
});
