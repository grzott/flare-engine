/**
 * check-nodenext — prove every publishable package's `exports` map resolves to
 * type declarations for a Node / Metro (nodenext) consumer. Dev typechecks with
 * `moduleResolution: bundler`, which never exercises the published exports map;
 * this closes that gap (the F1 finding) with a check `check-exports` does not
 * duplicate: it imports each package by its PUBLIC specifier through the real,
 * installed node_modules graph, so a broken entry point surfaces as a consumer
 * TS2307 rather than a per-tarball attw report.
 *
 * A fresh probe is generated from the live package list on every run (so it can
 * never drift out of sync). It namespace-imports every package's root AND every
 * declared subpath export (so a future `exports["./headless"]` is covered too),
 * then typechecks with `module`/`moduleResolution: nodenext`. `.mts` is always an
 * ES module, so this validates the `import` condition (→ `.d.mts`); attw covers
 * `require`. `skipLibCheck` is required to tolerate un-installed peer types
 * (react-native, canvaskit-wasm, …) inside package `.d.ts` files — so this
 * validates ENTRY-POINT resolution, not deep `.d.ts` contents; attw validates
 * per-tarball exports self-consistency and publint the manifest. Requires
 * `bun run build` first (resolution targets `dist/`).
 *
 * Bun-runnable plain ESM. Exit 1 if any exports entry fails to resolve.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES_DIR = join(ROOT, 'packages');
const PROBE_DIR = join(ROOT, 'scripts', 'nodenext-probe');
const PROBE_FILE = join(PROBE_DIR, 'probe.generated.mts');
const TSCONFIG = join(PROBE_DIR, 'tsconfig.json');
const BUN = process.execPath;
const IGNORE = new Set(['benchmarks']);

// Public import specifiers for a package: its root plus every declared subpath
// export (skipping ./package.json and wildcard patterns, which aren't literally
// importable). Falls back to the bare name when there is no subpath map.
const specifiersFor = (name, exportsField) => {
  if (!exportsField || typeof exportsField === 'string') return [name];
  const keys = Object.keys(exportsField).filter((k) => k.startsWith('.'));
  if (keys.length === 0) return [name];
  const specs = [];
  for (const k of keys) {
    if (k === './package.json' || k.includes('*')) continue;
    specs.push(k === '.' ? name : `${name}/${k.slice(2)}`);
  }
  return specs.length > 0 ? specs : [name];
};

const specifiers = [];
for (const dir of readdirSync(PACKAGES_DIR).sort()) {
  const pj = join(PACKAGES_DIR, dir, 'package.json');
  if (!existsSync(pj) || IGNORE.has(dir)) continue;
  const j = JSON.parse(readFileSync(pj, 'utf8'));
  if (!j.name) continue;
  if (!existsSync(join(PACKAGES_DIR, dir, 'dist'))) {
    console.error(`check-nodenext: ${j.name} has no dist/ — run \`bun run build\` first.`);
    process.exit(1);
  }
  specifiers.push(...specifiersFor(j.name, j.exports));
}

const lines = [
  '// GENERATED by scripts/check-nodenext.mjs — do not edit, do not commit.',
  '// Namespace-imports every publishable package specifier so a nodenext consumer',
  '// typecheck validates each exports entry resolves to type declarations.',
  ...specifiers.map((spec, i) => `import * as p${i} from '${spec}';`),
  `export const _probed = [${specifiers.map((_, i) => `p${i}`).join(', ')}] as const;`,
  '',
];
writeFileSync(PROBE_FILE, lines.join('\n'));

try {
  execFileSync(BUN, ['x', 'tsc', '--noEmit', '-p', TSCONFIG], { cwd: ROOT, stdio: 'inherit' });
} catch {
  console.error('\ncheck-nodenext: FAILED — an exports entry does not resolve under nodenext.');
  console.error(`See the errors above; the generated probe is at ${PROBE_FILE}.`);
  process.exit(1);
}

console.log(`check-nodenext: OK — ${specifiers.length} specifier(s) resolve under nodenext.`);
process.exit(0);
